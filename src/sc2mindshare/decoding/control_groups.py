"""Control-group update kinds and client-generated control-group events (CR-047, T3-7).

The raw `update_type` of a control-group event, with upstream sc2reader's meaning (F3-012, supported on
three replays): 0 set, 1 add, 2 recall, 3 clear, 4 steal and set, 5 steal and add. The fork names 3, 4 and
5 differently; stream 1 keeps the fork's names until its ledger fix (TD-5), and this module exposes the
upstream meaning alongside.

After a steal (4 or 5) the client generates, in the same game loop, events that remove the stolen units
from the player's other groups: per group a recall, a selection change, then a set or (if the group is
now empty) a clear. They are not key presses, so they are counted apart ("auto"). Every clear in the three
replays is one of them.
"""

from __future__ import annotations

import enum
from collections import Counter, defaultdict
from typing import Any

from sc2reader.events.game import ControlGroupEvent, SelectionEvent  # type: ignore[import-untyped]


class Kind(enum.Enum):
    SET = 0
    ADD = 1
    RECALL = 2
    CLEAR = 3
    STEAL_SET = 4
    STEAL_ADD = 5
    UNKNOWN = -1
    SELECTION = -2  # a selection change, counted with the control-group events it may belong to


STEALS = (Kind.STEAL_SET, Kind.STEAL_ADD)


def kind_of(update_type: int) -> Kind:
    try:
        kind = Kind(update_type)
    except ValueError:
        return Kind.UNKNOWN
    return kind if kind not in (Kind.UNKNOWN, Kind.SELECTION) else Kind.UNKNOWN


def control_group_activity(replay: Any) -> dict[int, dict[tuple[Kind, str], int]]:
    """Per player id: control-group events by kind and selection changes, each marked "player" or "auto"
    (generated by the client in the same game loop as the player's latest steal)."""
    events: dict[int, list[Any]] = defaultdict(list)
    for event in replay.game_events:
        if event.player is not None and isinstance(event, (ControlGroupEvent, SelectionEvent)):
            events[event.player.pid].append(event)
    result = {}
    for pid, player_events in sorted(events.items()):
        counts: Counter[tuple[Kind, str]] = Counter()
        steal_loop = None
        for event in player_events:
            if isinstance(event, SelectionEvent):
                counts[(Kind.SELECTION, "auto" if event.frame == steal_loop else "player")] += 1
                continue
            kind = kind_of(event.update_type)
            if kind in STEALS:
                counts[(kind, "player")] += 1
                steal_loop = event.frame
            else:
                counts[(kind, "auto" if event.frame == steal_loop else "player")] += 1
        result[pid] = dict(counts)
    return result
