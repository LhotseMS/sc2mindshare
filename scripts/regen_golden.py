#!/usr/bin/env python3
"""Regenerate or re-check the goldens (CR-007; QA design §1.5, §5 C5/C6).

    scripts/py-env .venv/bin/python scripts/regen_golden.py --check
        Re-runs the legacy code and the VBA view port into a temp folder and compares
        the results with the frozen goldens (G-CSV-1, Intervals-1, G-VIEW-1). Changes nothing.

    scripts/py-env .venv/bin/python scripts/regen_golden.py --entry <id> --golden <name> [--replay spine] [--write]
        Regenerates a non-frozen golden (REGENERABLE) of a replay (REPLAYS; Alcyone by default) with the
        current code into a temp folder and runs the C3/C4 check of the CHANGES.md entry against the golden
        on disk. With --write, and only when the check passes, the golden is replaced.

        A golden that does not exist yet (CR-035, call 14: spine's current goldens) is made under an entry
        that changes nothing (the H1 pattern for a new file): its ``base_sha256`` is the new file's own
        sha256 and it lists no change, addition or removal. The check is C4 on the regenerated file; the
        same entry then passes ``check_golden_delta.py --old <file> --new <file>``.

The frozen goldens are never regenerated by this script: a change to one of them is a
stop-and-report for Kevin and Stefan (approach §7.2). G-SNAP-1 (frozen after B2, QA design Addendum B)
is a snapshot of the code at its confirmation, so --check does not re-run it; FROZEN.sha256 pins it.
"""

