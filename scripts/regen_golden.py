#!/usr/bin/env python3
"""Regenerate or re-check the Alcyone goldens (CR-007; QA design §1.5, §5 C5/C6).

    scripts/py-env .venv/bin/python scripts/regen_golden.py --check
        Re-runs the legacy code and the VBA view port into a temp folder and compares
        the results with the frozen goldens (G-CSV-1, Intervals-1, G-VIEW-1). Changes nothing.

    scripts/py-env .venv/bin/python scripts/regen_golden.py --entry <id> --golden <name> [--write]
        Regenerates a non-frozen golden (REGENERABLE) with the current code into a temp folder and
        runs the C3/C4 check of the CHANGES.md entry against the golden on disk. With --write, and
        only when the check passes, the golden is replaced.

The frozen goldens are never regenerated by this script: a change to one of them is a
stop-and-report for Kevin and Stefan (approach §7.2).
"""

from __future__ import annotations

import argparse
import contextlib
import csv
import hashlib
import importlib.util
import io
import json
import shutil
import subprocess
import sys
import tempfile
from collections.abc import Callable
from pathlib import Path

from sc2mindshare.analysis.run import analyse
from sc2mindshare.analysis.to_domain import to_graph
from sc2mindshare.domain.models import Graph
from sc2mindshare.export.mindshare_json import build_document, to_json
from sc2mindshare.layout.items import items
from sc2mindshare.layout.profile import Profile, Timeline
from sc2mindshare.layout.sweep import layout
from sc2mindshare.reader.loader import load_replay

CHECKOUT = Path(__file__).resolve().parents[1]
GOLDEN = CHECKOUT / "tests" / "golden" / "alcyone"
FROZEN = {"G-CSV-1.csv", "Intervals-1.csv", "G-VIEW-1.json"}
CHANGES = CHECKOUT / "tests" / "golden" / "CHANGES.md"

_spec = importlib.util.spec_from_file_location("golden", CHECKOUT / "tests" / "golden" / "golden.py")
assert _spec and _spec.loader
golden = importlib.util.module_from_spec(_spec)
sys.modules["golden"] = golden
_spec.loader.exec_module(golden)
_spec = importlib.util.spec_from_file_location("check_golden_delta", CHECKOUT / "scripts" / "check_golden_delta.py")
assert _spec and _spec.loader
check_golden_delta = importlib.util.module_from_spec(_spec)
sys.modules["check_golden_delta"] = check_golden_delta
_spec.loader.exec_module(check_golden_delta)


def root() -> Path:
    d = CHECKOUT
    while d != d.parent and not (d / ".tools").is_dir():
        d = d.parent
    return d


def _alcyone() -> Path:
    return root() / "MS SC" / "Alcyone LE__lilTiGGer_vs_blacksquall" / "Alcyone LE__lilTiGGer_vs_blacksquall.SC2Replay"


def _graph() -> Graph:
    """The current domain graph of Alcyone (fixes applied), from a freshly loaded replay."""
    with contextlib.redirect_stdout(io.StringIO()):  # the moved legacy layer prints debug text
        return to_graph(analyse(load_replay(_alcyone()), root() / "MS SC"))


def _view_current() -> str:
    return to_json(build_document(_graph()))


def _snapshot(mode: Timeline) -> Callable[[], str]:
    def make() -> str:
        with (root() / "MS SC" / "TimeImageTracking.csv").open(encoding="utf-8") as f:
            clock_map = {r["imageName"]: r["imageID"] for r in csv.DictReader(f)}
        graph = _graph()
        return to_json(build_document(graph, layout(items(graph), Profile(timeline=mode), clock_map)))

    return make


#: Non-frozen goldens: file name -> how the current code makes it.
REGENERABLE: dict[str, Callable[[], str]] = {
    "G-VIEW-current.json": _view_current,
    "G-SNAP-1-compressed.json": _snapshot("compressed"),
    "G-SNAP-1-linear.json": _snapshot("linear"),
}


def _was_in_history(name: str, sha256: str) -> bool:
    """Whether some committed version of the golden had this sha256 (the entry's base, applied since)."""
    rel = f"tests/golden/alcyone/{name}"
    log = subprocess.run(
        ["git", "-C", str(CHECKOUT), "log", "--format=%H", "--", rel], check=True, capture_output=True, text=True
    ).stdout.split()
    for sha in log:
        blob = subprocess.run(["git", "-C", str(CHECKOUT), "show", f"{sha}:{rel}"], check=False, capture_output=True)
        if blob.returncode == 0 and hashlib.sha256(blob.stdout).hexdigest() == sha256:
            return True
    return False


def regenerate(entry_id: str, name: str, write: bool) -> int:
    """Make ``name`` with the current code, check it against the entry (C3, C4), write it if asked."""
    entry = check_golden_delta.entries(CHANGES.read_text(encoding="utf-8")).get(entry_id)
    if entry is None:
        print(f"no entry {entry_id!r} in CHANGES.md: write the entry first")
        return 2
    if f"alcyone/{name}" not in entry["golden"]:
        print(f"entry {entry_id} does not list alcyone/{name}")
        return 2
    clock_map = golden.load_clock_map(root() / "MS SC" / "TimeImageTracking.csv")
    text = REGENERABLE[name]()
    on_disk = GOLDEN / name
    applied = golden.sha256(on_disk) != entry["base_sha256"] and _was_in_history(name, entry["base_sha256"])
    if text == on_disk.read_text(encoding="utf-8") and applied:
        # the golden is the code's output, and the entry's base is an earlier version of it: applied before
        print(f"{name}: entry {entry_id} is already applied (the golden is the code's output); nothing written")
        return 0
    with tempfile.TemporaryDirectory() as tmp:
        new = Path(tmp) / name
        new.write_text(text, encoding="utf-8")
        problems = check_golden_delta.check_delta(entry, GOLDEN / name, new, clock_map)
        for p in problems:
            print(p)
        if problems:
            print(f"{name}: the regenerated golden does not match entry {entry_id}; nothing written")
            return 1
        print(f"{name}: matches entry {entry_id} (sha256 {golden.sha256(new)})")
        if write:
            shutil.copyfile(new, GOLDEN / name)
            print(f"{name}: written")
    return 0


def check() -> int:
    ms_sc = root() / "MS SC"
    replay = ms_sc / "Alcyone LE__lilTiGGer_vs_blacksquall" / "Alcyone LE__lilTiGGer_vs_blacksquall.SC2Replay"
    legacy = CHECKOUT / ".venv-legacy" / "bin" / "python"
    problems = []
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp)
        cmd = [str(legacy), str(CHECKOUT / "scripts" / "run_legacy.py"), "--support", str(ms_sc), "--out", str(out), str(replay)]
        subprocess.run(cmd, check=True, capture_output=True)
        csv_report = golden.diff_csv(
            (GOLDEN / "G-CSV-1.csv").read_text(encoding="utf-8"), (out / replay.stem / "events.csv").read_text(encoding="utf-8")
        )
        if not csv_report.ok:
            problems.append(f"G-CSV-1: {csv_report}")
        if (out / replay.stem / "Intervals.csv").read_bytes() != (GOLDEN / "Intervals-1.csv").read_bytes():
            problems.append("Intervals-1: differs")
        view_out = out / "view.json"
        subprocess.run(
            [
                sys.executable,
                str(CHECKOUT / "tests" / "reference" / "vba_view" / "make_view.py"),
                str(GOLDEN / "G-CSV-1.csv"),
                str(view_out),
                "--rejoin-raw-newlines",
            ],
            check=True,
            capture_output=True,
        )
        view_report = golden.diff_json(
            json.loads((GOLDEN / "G-VIEW-1.json").read_text(encoding="utf-8")), json.loads(view_out.read_text(encoding="utf-8"))
        )
        if not view_report.ok:
            problems.append(f"G-VIEW-1: {view_report}")
    for p in problems:
        print(p)
    print("frozen goldens reproduce" if not problems else "STOP: a frozen golden no longer reproduces; report to Kevin")
    return 0 if not problems else 1


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--entry")
    parser.add_argument("--golden")
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args(argv)
    if args.entry or args.golden:
        if args.golden in FROZEN:
            print(f"{args.golden} is frozen: never regenerated (stop and report)")
            return 2
        if args.golden not in REGENERABLE:
            print(f"no regenerable golden named {args.golden!r}; regenerable: {sorted(REGENERABLE)}")
            return 2
        if not args.entry:
            print("--entry is required: every golden change needs its CHANGES.md entry")
            return 2
        return regenerate(args.entry, args.golden, args.write)
    return check()


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
