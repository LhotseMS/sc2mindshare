from sc2mindshare.analysis.run import analyse
from sc2mindshare.analysis.to_domain import to_graph
from sc2mindshare.domain.models import Graph
from sc2mindshare.export.mindshare_json import build_document, to_json
from sc2mindshare.layout.items import items
from sc2mindshare.layout.profile import Profile, Timeline
from sc2mindshare.layout.sweep import layout
from sc2mindshare.reader.loader import load_replay

CHECKOUT = Path(__file__).resolve().parents[1]
GOLDEN = CHECKOUT / "tests" / "golden" / "alcyone"
#: The replays with current goldens: name -> the replay file under MS SC (CR-035, call 14 adds spine).
REPLAYS = {
    "alcyone": Path("Alcyone LE__lilTiGGer_vs_blacksquall") / "Alcyone LE__lilTiGGer_vs_blacksquall.SC2Replay",
    "spine": Path("200k dmg spine crawler ZvP.SC2Replay"),
}
FROZEN = {"G-CSV-1.csv", "Intervals-1.csv", "G-VIEW-1.json", "G-SNAP-1-compressed.json", "G-SNAP-1-linear.json"}
CHANGES = CHECKOUT / "tests" / "golden" / "CHANGES.md"

_spec = importlib.util.spec_from_file_location("golden", CHECKOUT / "tests" / "golden" / "golden.py")
assert _spec and _spec.loader
golden = importlib.util.module_from_spec(_spec)
sys.modules["golden"] = golden
_spec.loader.exec_module(golden)
_spec = importlib.util.spec_from_file_location("check_golden_delta", CHECKOUT / "scripts" / "check_golden_delta.py")
assert _spec and _spec.loader
check_golden_delta = importlib.util.module_from_spec(_spec)
sys.modules["check_golden_delta"] = check_golden_delta
_spec.loader.exec_module(check_golden_delta)


def root() -> Path:
    d = CHECKOUT
    while d != d.parent and not (d / ".tools").is_dir():
        d = d.parent
    return d


def replay_path(replay: str = "alcyone") -> Path:
    return root() / "MS SC" / REPLAYS[replay]


def _alcyone() -> Path:
    return replay_path("alcyone")


def golden_dir(replay: str = "alcyone") -> Path:
    return CHECKOUT / "tests" / "golden" / replay


def _graph(replay: str = "alcyone") -> Graph:
    """The current domain graph of a replay (fixes applied), from a freshly loaded replay."""
    with contextlib.redirect_stdout(io.StringIO()):  # the moved legacy layer prints debug text
        return to_graph(analyse(load_replay(replay_path(replay)), root() / "MS SC"))


def _view_current(replay: str = "alcyone") -> str:
    return to_json(build_document(_graph(replay)))


def _snapshot(mode: Timeline) -> Callable[..., str]:
    def make(replay: str = "alcyone") -> str:
        clock_map = golden.fixture_clock_map()  # CR-069: the committed fixture record (localhost:3042)
        graph = _graph(replay)
        return to_json(build_document(graph, layout(items(graph), Profile(timeline=mode), clock_map)))

    return make


#: Non-frozen goldens: file name -> how the current code makes it (for the replay it is given).
REGENERABLE: dict[str, Callable[..., str]] = {
    "G-VIEW-current.json": _view_current,
    "G-SNAP-current-compressed.json": _snapshot("compressed"),
    "G-SNAP-current-linear.json": _snapshot("linear"),
}


def history_names(name: str, replay: str = "alcyone") -> list[str]:
    """The golden, then the frozen golden a freeze entry copied to it (QA design Addendum B): an entry moved
    to the live copy has its base in the frozen file's history, from before the freeze."""
    names = [name]
    for entry in check_golden_delta.entries(CHANGES.read_text(encoding="utf-8")).values():
        names += [Path(frozen).name for frozen, live in entry.get("copies", {}).items() if live == f"{replay}/{name}"]
    return names


def _was_in_history(name: str, sha256: str, repo: Path = CHECKOUT, replay: str = "alcyone") -> bool:
    """Whether some committed version of the golden had this sha256 (the entry's base, applied since).
    Outside a git repository (a ``git archive`` copy) the history cannot be read: False, so the entry
    goes to the ordinary C3/C4 check."""
    rel = f"tests/golden/{replay}/{name}"
    env = check_golden_delta.git_env()  # no GIT_DIR or GIT_WORK_TREE can point git at another repository
    log = subprocess.run(
        ["git", "-C", str(repo), "log", "--format=%H", "--", rel], check=False, capture_output=True, text=True, env=env
    )
    if log.returncode != 0:
        print("history unavailable (not a git repository): checking against the entry's base")
        return False
    for sha in log.stdout.split():
        blob = subprocess.run(["git", "-C", str(repo), "show", f"{sha}:{rel}"], check=False, capture_output=True, env=env)
        if blob.returncode == 0 and hashlib.sha256(blob.stdout).hexdigest() == sha256:
            return True
    return False


def _new_file(entry: dict[str, Any], text: str, on_disk: Path, write: bool) -> int:
    """A golden that does not exist yet (the H1 pattern for a new file, CR-035 call 14): the entry changes
    nothing, and its base is the new file's own sha256 (C4 on the regenerated text)."""
    if entry.get("changes") or entry.get("added") or entry.get("removed") or entry.get("renumber"):
        print(f"{on_disk.name}: no golden on disk, and entry {entry['entry']} lists changes: a new golden's entry lists none")
        return 1
    sha = hashlib.sha256(text.encode("utf-8")).hexdigest()
    if sha != entry["base_sha256"]:
        print(f"C4 base_sha256 does not match the new {on_disk.name} (sha256 {sha}); nothing written")
        return 1
    print(f"{on_disk.name}: new golden, matches entry {entry['entry']} (sha256 {sha})")
    if write:
        on_disk.write_text(text, encoding="utf-8")
        print(f"{on_disk.name}: written")
    return 0


def regenerate(entry_id: str, name: str, write: bool, replay: str = "alcyone") -> int:
    """Make ``name`` with the current code, check it against the entry (C3, C4), write it if asked."""
    entry = check_golden_delta.entries(CHANGES.read_text(encoding="utf-8")).get(entry_id)
    if entry is None:
        print(f"no entry {entry_id!r} in CHANGES.md: write the entry first")
        return 2
    if f"{replay}/{name}" not in entry["golden"]:
        print(f"entry {entry_id} does not list {replay}/{name}")
        return 2
    clock_map = golden.load_clock_map(root() / "MS SC" / "TimeImageTracking.csv")
    text = REGENERABLE[name](replay)
    on_disk = golden_dir(replay) / name
    if not on_disk.exists():
        return _new_file(entry, text, on_disk, write)
    applied = golden.sha256(on_disk) != entry["base_sha256"] and any(
        _was_in_history(n, entry["base_sha256"], replay=replay) for n in history_names(name, replay)
    )
    if text == on_disk.read_text(encoding="utf-8") and applied:
        # the golden is the code's output, and the entry's base is an earlier version of it: applied before
        print(f"{name}: entry {entry_id} is already applied (the golden is the code's output); nothing written")
        return 0
    with tempfile.TemporaryDirectory(dir=scratch()) as tmp:
        new = Path(tmp) / name
        new.write_text(text, encoding="utf-8")
        problems = check_golden_delta.check_delta(entry, on_disk, new, clock_map)
        for p in problems:
            print(p)
        if problems:
            print(f"{name}: the regenerated golden does not match entry {entry_id}; nothing written")
            return 1
        print(f"{name}: matches entry {entry_id} (sha256 {golden.sha256(new)})")
        if write:
            shutil.copyfile(new, on_disk)
            print(f"{name}: written")
    return 0


def scratch() -> Path:
    """Where temporary folders go: <root>/.tools/tmp, never the caller's TMPDIR (D30a)."""
    path = root() / ".tools" / "tmp"
    path.mkdir(parents=True, exist_ok=True)
    return path


def check() -> int:
    ms_sc = root() / "MS SC"
    replay = ms_sc / "Alcyone LE__lilTiGGer_vs_blacksquall" / "Alcyone LE__lilTiGGer_vs_blacksquall.SC2Replay"
    legacy = CHECKOUT / ".venv-legacy" / "bin" / "python"
    problems = []
    with tempfile.TemporaryDirectory(dir=scratch()) as tmp:
        out = Path(tmp)
        cmd = [str(legacy), str(CHECKOUT / "scripts" / "run_legacy.py"), "--support", str(ms_sc), "--out", str(out), str(replay)]
        subprocess.run(cmd, check=True, capture_output=True)
        csv_report = golden.diff_csv(
            (GOLDEN / "G-CSV-1.csv").read_text(encoding="utf-8"), (out / replay.stem / "events.csv").read_text(encoding="utf-8")
        )
        if not csv_report.ok:
            problems.append(f"G-CSV-1: {csv_report}")
        if (out / replay.stem / "Intervals.csv").read_bytes() != (GOLDEN / "Intervals-1.csv").read_bytes():
            problems.append("Intervals-1: differs")
        view_out = out / "view.json"
        subprocess.run(
            [
                sys.executable,
                str(CHECKOUT / "tests" / "reference" / "vba_view" / "make_view.py"),
                str(GOLDEN / "G-CSV-1.csv"),
                str(view_out),
                "--rejoin-raw-newlines",
            ],
            check=True,
            capture_output=True,
        )
        view_report = golden.diff_json(
            json.loads((GOLDEN / "G-VIEW-1.json").read_text(encoding="utf-8")), json.loads(view_out.read_text(encoding="utf-8"))
        )
        if not view_report.ok:
            problems.append(f"G-VIEW-1: {view_report}")
    for p in problems:
        print(p)
    print("frozen goldens reproduce" if not problems else "STOP: a frozen golden no longer reproduces; report to Kevin")
    return 0 if not problems else 1


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--entry")
    parser.add_argument("--golden")
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--replay", choices=sorted(REPLAYS), default="alcyone")
    args = parser.parse_args(argv)
    if args.entry or args.golden:
        if args.golden in FROZEN:
            print(f"{args.golden} is frozen: never regenerated (stop and report)")
            return 2
        if args.golden not in REGENERABLE:
            print(f"no regenerable golden named {args.golden!r}; regenerable: {sorted(REGENERABLE)}")
            return 2
        if not args.entry:
            print("--entry is required: every golden change needs its CHANGES.md entry")
            return 2
        return regenerate(args.entry, args.golden, args.write, args.replay)
    return check()


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
